"""UrbanRay geometry-aware regression + specialist reflection-hotspot model.

Train/choose using existing development dates and geometry blocks; the archived
June 23, 2025 lockbox has ALREADY BEEN INSPECTED in earlier evaluation runs.
This is a retrospective benchmark, NOT a fresh independent evaluation.
All targets are generated by the approximate shortwave PHYSICS SIMULATOR.
"""
from __future__ import annotations
import argparse
import hashlib
import json
import shutil
import sys
from pathlib import Path
from time import perf_counter

import joblib
import numpy as np
import pandas as pd
import sklearn
from sklearn.ensemble import HistGradientBoostingRegressor
from sklearn.metrics import mean_absolute_error, mean_squared_error

ROOT=Path(__file__).resolve().parent
sys.path.insert(0,str(ROOT/'src'))
from geometry_features import augment_full_scene_table,GEOMETRY_FEATURES
from ai_inference import ENHANCED_MODEL_FEATURES,MODEL_FEATURES
from train_surrogate import load_training,split

TARGET='multibounce_abs_Wm2'
BASE='direct_plus_sky_abs_Wm2'
FEATURES=list(ENHANCED_MODEL_FEATURES)
PARAMS=[
    {'max_iter':180,'max_leaf_nodes':19,'learning_rate':.065,'l2_regularization':1.0},
    {'max_iter':260,'max_leaf_nodes':25,'learning_rate':.045,'l2_regularization':3.0},
]


def predict(model, df, transform='none', features=FEATURES):
    raw=np.asarray(model.predict(df[list(features)]),float)
    if transform=='log1p':raw=np.expm1(np.clip(raw,-30.,30.))
    return df[BASE].to_numpy(float)+np.maximum(0.,raw)


def hotspot_capture(frame:pd.DataFrame, prediction:np.ndarray, k:int=20) -> dict:
    """Held-out scene-day, one scenario, all wall patches; no labels in ranking."""
    if len(frame)!=len(prediction):raise ValueError('Prediction length mismatch')
    d=frame.loc[(frame.kind=='wall')&(frame.scenario=='dark_roof'),
        ['face_id','time_utc',TARGET,BASE]].copy()
    if d.empty:return {'captured_percent':0.,'overlap':0,'wall_patches':0}
    # Frame index can differ from 0..n, so gather with boolean mask positions.
    mask=((frame.kind=='wall')&(frame.scenario=='dark_roof')).to_numpy()
    d['prediction']=prediction[mask]
    if d.duplicated(['time_utc','face_id']).any():raise ValueError('Duplicate wall patch-hour')
    day=d.groupby('face_id').agg(truth=(TARGET,'sum'),base=(BASE,'sum'),
                                pred=('prediction','sum'),hours=('time_utc','nunique'))
    if not (day.hours==24).all():raise ValueError('Hotspot evaluation requires 24 complete hours')
    truth=(day.truth-day.base).clip(lower=0)
    predicted=(day.pred-day.base).clip(lower=0)
    # A reflection-blind baseline has zero residual everywhere, so compare
    # its ACTUAL cheap direct-exposure ranking rather than arbitrary ties.
    if np.allclose(prediction,frame[BASE].to_numpy(float),rtol=0,atol=1e-9):
        predicted=day.base
    k=min(k,len(day))
    oracle=truth.nlargest(k).index
    ours=predicted.nlargest(k).index
    maximum=float(truth.loc[oracle].sum())
    return {'captured_percent':float(100*truth.loc[ours].sum()/maximum) if maximum>0 else 0.,
            'overlap':int(len(oracle.intersection(ours))),
            'wall_patches':int(len(day)), 'k':k}


def _fit(data,params, *, transform='none', weighted=False, seed=62,features=FEATURES):
    target=np.maximum(0.,(data[TARGET]-data[BASE]).to_numpy(float))
    y=np.log1p(target) if transform=='log1p' else target
    weights=None
    if weighted:
        scale=max(float(np.percentile(target,90)),1.)
        weights=1+2.5*np.clip(target/scale,0,4)
    model=HistGradientBoostingRegressor(**params,random_state=seed,
                                       min_samples_leaf=20)
    model.fit(data[list(features)],y,sample_weight=weights)
    return model


def _bundle(model,name,transform,extra):
    return {'model':model,'features':FEATURES,'target':TARGET,
        'prediction_mode':'residual','target_transform':transform,
        'sklearn_version':sklearn.__version__,
        'feature_method':'local sparse neighboring-surface geometric proxy; no occlusion',
        'model_role':name,'source_hash':extra['source_file_sha256'],
        'training_evidence':'SIMULATED shortwave labels; real geometry, assumed materials',
        'evaluation_lockbox':'June 23, 2025 test was already inspected during model evaluation',
        'observed_rooftop_temperature_accuracy':False}


def make_report(train:pd.DataFrame,val:pd.DataFrame,test:pd.DataFrame,out:Path,meta:dict,
                previous_file:Path,seed=62,limit_train=45000):
    out.mkdir(parents=True,exist_ok=True)
    train_fit=train.sample(limit_train,random_state=seed) if len(train)>limit_train else train
    selection=[];reg_candidates=[];hot_candidates=[]
    for params in PARAMS:
        for transform,weighted,role in [('none',False,'regression'),
                                         ('log1p',True,'hotspot')]:
            model=_fit(train_fit,params,transform=transform,weighted=weighted,seed=seed)
            prediction=predict(model,val,transform)
            rec={'role':role,'transform':transform,'parameters':params,
                 'validation_mae_Wm2':float(mean_absolute_error(val[TARGET],prediction)),
                 'validation_wall_hotspot_top20':hotspot_capture(val,prediction)}
            selection.append(rec)
            (reg_candidates if role=='regression' else hot_candidates).append((rec,model))
    # Validation-only choice. The hotspot model is selected for captured
    # simulated exposure, not for test accuracy or dashboard attractiveness.
    chosen_reg=min(reg_candidates,key=lambda item:item[0]['validation_mae_Wm2'])[0]
    chosen_hot=max(hot_candidates,key=lambda item:(item[0]['validation_wall_hotspot_top20']['captured_percent'],
                   -item[0]['validation_mae_Wm2']))[0]
    combo=pd.concat([train_fit,val],ignore_index=True)
    models={}
    for role,record in [('regression',chosen_reg),('hotspot',chosen_hot)]:
        mdl=_fit(combo,record['parameters'],transform=record['transform'],
                 weighted=(role=='hotspot'),seed=seed)
        models[role]=(mdl,record['transform'])
        joblib.dump(_bundle(mdl,role,record['transform'],meta),out/f'{role}_surrogate.joblib')
    shutil.copyfile(out/'regression_surrogate.joblib',out/'selected_surrogate.joblib')
    current={role:predict(m,test,transform) for role,(m,transform) in models.items()}
    # Controlled feature ablation: identical fitting rows, regressor params,
    # targets and refit schedule; only neighborhood columns are removed.
    ablation=_fit(combo,chosen_reg['parameters'],seed=seed,features=MODEL_FEATURES)
    without_geometry=predict(ablation,test,features=MODEL_FEATURES)
    joblib.dump(_bundle(ablation,'controlled_ablation_no_geometry','none',meta)|
               {'features':list(MODEL_FEATURES)},out/'ablation_without_geometry_surrogate.joblib')
    previous=pd.read_csv(previous_file,dtype={'building_id':str})
    keys=['time_utc','scenario','face_id']
    if previous.duplicated(keys).any():raise ValueError('Prior benchmark contains duplicate keys')
    # Align exact historical lockbox rows, never blindly positional join.
    base_frame=test[keys].reset_index(drop=True)
    prev=base_frame.merge(previous,on=keys,how='left',validate='one_to_one',sort=False)
    if len(prev)!=len(test) or prev['pred_Reflection-residual_AI'].isna().any():
        raise ValueError('Earlier benchmark does not contain the same historical lockbox rows')
    prior=prev['pred_Reflection-residual_AI'].to_numpy(float)
    physics_base=test[BASE].to_numpy(float)
    preds={'No-reflection':physics_base,'Previously published residual AI':prior,
           'Controlled ablation (same training, no geometry)':without_geometry,
           'Geometry-aware regression':current['regression'],
           'Dedicated hotspot AI':current['hotspot']}
    y=test[TARGET].to_numpy(float)
    scores=[]
    high=(np.maximum(0,y-physics_base)>=np.percentile(np.maximum(0,y-physics_base),90))
    for name,pred in preds.items():
        scores.append({'model':name,'test_mae_Wm2':float(mean_absolute_error(y,pred)),
           'test_rmse_Wm2':float(np.sqrt(mean_squared_error(y,pred))),
           'top10_percent_reflection_test_mae_Wm2':float(mean_absolute_error(y[high],pred[high])),
           'wall_hotspot_top20':hotspot_capture(test,pred),'num_face_hours':len(y)})
    score_table=pd.DataFrame([{k:v for k,v in r.items() if k!='wall_hotspot_top20'} |
         {'captured_top20_percent':r['wall_hotspot_top20']['captured_percent'],
          'top20_overlap':r['wall_hotspot_top20']['overlap']} for r in scores])
    score_table.to_csv(out/'retrospective_model_comparison_SIMULATED.csv',index=False)
    pred_table=test[['time_utc','date_utc','scenario','face_id','building_id','kind','spatial_block']].copy().reset_index(drop=True)
    pred_table['physics_label_Wm2']=y
    pred_table['pred_No-reflection_physics']=physics_base
    pred_table['pred_Reflection-residual_AI']=current['regression']
    pred_table['pred_Legacy_residual_AI']=prior
    pred_table['pred_Hotspot_AI']=current['hotspot']
    pred_table['pred_Ablation_no_geometry_AI']=without_geometry
    # Preserve the original fair same-lockbox direct-ML and mean baselines.
    for column in ('pred_Direct_AI','pred_Mean-only'):
        if column not in prev or prev[column].isna().any():
            raise ValueError(f'Archived comparator absent or incomplete: {column}')
        pred_table[column]=prev[column].to_numpy(float)
    pred_table.to_csv(out/'retrospective_heldout_predictions_SIMULATED.csv',index=False)
    report={**meta,'splits':{'train':len(train),'validation':len(val),'previously_seen_test':len(test)},
        'train_subsample':len(train_fit),'refit_train_plus_validation':len(combo),
        'feature_names':FEATURES,'local_geometry_proxy_has_occlusion':False,
        'model_selection':'only June 22 validation; June 23 old test read after selection',
        'selection':selection,'chosen_regression':chosen_reg,'chosen_hotspot':chosen_hot,
        'results_on_previously_inspected_test':scores,
        'real_observation_validation_completed':False,
        'independent_new_lockbox_available':False,
        'claim':'This release reports exploratory comparison to simulated physics, NOT unseen field validation'}
    (out/'model_audit.json').write_text(json.dumps(report,indent=2))
    return score_table,report


def main():
    p=argparse.ArgumentParser()
    p.add_argument('--faces',type=Path,default=ROOT/'outputs/historical_ml/physics_training_faces.csv')
    p.add_argument('--previous',type=Path,default=ROOT/'outputs/ai_upgrade/reflection_residual/candidate_heldout_predictions.csv')
    p.add_argument('--out',type=Path,default=ROOT/'outputs/geometry_ai_upgrade')
    p.add_argument('--train-limit',type=int,default=45000)
    args=p.parse_args()
    start=perf_counter()
    print('Reading original simulation faces, no generated/observed labels...',flush=True)
    df=load_training(args.faces)
    print('Computing sparse neighboring-surface features for full time-matched meshes...',flush=True)
    df,graph=augment_full_scene_table(df)
    train,val,test,part=split(df)
    meta={'source_file_sha256':hashlib.sha256(args.faces.read_bytes()).hexdigest(),
          'graph':graph.params,'partition':part}
    print(f'Learning on {len(train)} train / {len(val)} validation; test {len(test)} previously reviewed rows...',flush=True)
    table,report=make_report(train,val,test,args.out,meta,args.previous,limit_train=args.train_limit)
    report['elapsed_s_including_io']=round(perf_counter()-start,3)
    (args.out/'model_audit.json').write_text(json.dumps(report,indent=2))
    print(table.to_string(index=False)); print('SAVED:',args.out,flush=True)

if __name__=='__main__':main()
